function pixnoteBitmap(bitmap: string, additions: readonly number[] = []): number[] {
  if (!/^[\da-f]{64}$/.test(bitmap)) throw new Error("Pixnote bitmap must encode 16 rows of 16 pixels.");
  const occupied = Array.from({ length: 16 }, (_, y) => Number.parseInt(bitmap.slice(y * 4, y * 4 + 4), 16));
  additions.forEach((point) => {
    const x = point % 16;
    const y = Math.floor(point / 16);
    occupied[y] = occupied[y]! | (1 << (15 - x));
  });
  return occupied;
}

function rowsFromBitmap(occupied: readonly number[]): readonly string[] {
  return occupied.map((row, y) => Array.from({ length: 16 }, (_, x) => {
    if ((row & (1 << (15 - x))) === 0) return ".";
    const edge = [-1, 0, 1].some((dy) => [-1, 0, 1].some((dx) => {
      if (dx === 0 && dy === 0) return false;
      const nx = x + dx;
      const ny = y + dy;
      return nx < 0 || nx >= 16 || ny < 0 || ny >= 16
        || (occupied[ny]! & (1 << (15 - nx))) === 0;
    }));
    return edge ? "o" : "b";
  }).join(""));
}

